# ══════════════════════════════════════════════════════════
# 翻译函数
# ══════════════════════════════════════════════════════════


def t(key: str, lang: str = DEFAULT_LANGUAGE, **kwargs) -> str:
    """翻译指定语言的字符串

    参数:
        key: 翻译键，如 "report.title"
        lang: 语言代码，如 "zh", "en", "ja", "ko"
        **kwargs: 格式化参数，如 count=5 → "{count} 条" → "5 条"

    返回:
        翻译后的字符串，缺失键回退到中文
    """
    # 获取目标语言翻译，缺失时回退到中文
    lang_table = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE])
    text = lang_table.get(key)

    if text is None:
        # 回退到中文
        zh_table = TRANSLATIONS[DEFAULT_LANGUAGE]
        text = zh_table.get(key, key)

    # 格式化参数
    if kwargs:
        try:
            text = text.format(**kwargs)
        except KeyError:
            pass

    return text


def supported_languages() -> Dict[str, str]:
    """获取支持的语言列表

    返回: {代码: 显示名}
    """
    return dict(SUPPORTED_LANGUAGES)


def is_supported(lang: str) -> bool:
    """检查语言是否受支持"""
    return lang in TRANSLATIONS
